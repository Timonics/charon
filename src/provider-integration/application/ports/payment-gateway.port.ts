import type { ProviderName } from '../../../shared/kernel/provider-name';
import type { DomainError } from '../../../shared/kernel/domain-error';
import type { Result } from '../../../shared/kernel/result';

/**
 * The charge half of the provider port — the outbound direction. Webhook
 * adapters bring provider facts IN (see {@link ProviderWebhookPort}); this
 * interface takes commands OUT to the provider's API. Kept as a separate
 * interface so the two directions can be faked, deployed, and reasoned about
 * independently.
 *
 * The reconciliation contract that ties the two directions together:
 *
 *    InitializedCharge.providerReference
 *      == the value the provider's webhook adapter puts in
 *         NormalizedPaymentEvent.providerRef
 *
 * The Payments application layer stores the former on the PaymentIntent at
 * initiation and matches webhooks by the latter — if an adapter violates
 * this contract, Defense 2 of the webhook pipeline (unknown reference)
 * rejects every one of its events, loudly, at integration time.
 *
 * How each adapter satisfies it:
 *  - Paystack/Flutterwave: WE supply `reference` at initialize and the
 *    provider echoes it in webhook payloads — the returned
 *    providerReference is that same reference.
 *  - Stripe: the PaymentIntent id (pi_...) is generated BY Stripe, so the
 *    adapter returns it and the webhook adapter reads `payment_intent` —
 *    the two ids agree by construction.
 */

/** Input to {@link PaymentGatewayPort.initializeCharge}. */
export interface InitializeChargeInput {
  /**
   * OUR reference for this charge — the caller's idempotency anchor and, for
   * Paystack/Flutterwave, the exact value sent to the provider. Must be
   * unique per charge attempt; uniqueness is the caller's job (the
   * PaymentIntent id is the natural choice).
   */
  readonly reference: string;
  /** Integer minor units (kobo/cents) — never a float. */
  readonly amountMinor: number;
  /** Uppercase ISO 4217 code, e.g. 'NGN'. */
  readonly currency: string;
  /** Customer email — required by every supported provider's charge API. */
  readonly customerEmail: string;
  /**
   * Where the provider should redirect the customer after a hosted payment
   * page. Optional because not every flow uses one (e.g. Stripe's
   * client-secret flow embeds instead of redirecting).
   */
  readonly callbackUrl?: string;
  /** Opaque key/value pairs echoed back by providers; audit glue. */
  readonly metadata?: Record<string, string>;
}

/**
 * A charge the provider has accepted for processing. `checkoutUrl` and
 * `clientSecret` are mutually-flow-dependent: hosted-page providers fill
 * `checkoutUrl`, Stripe fills `clientSecret` for an embedded Payment
 * Element. Exactly one is present for every supported provider today, but
 * the shape tolerates either so the port doesn't dictate UI strategy.
 */
export interface InitializedCharge {
  /**
   * THE reconciliation key — see the interface doc. Stored on the internal
   * PaymentIntent and matched against webhook `providerRef`.
   */
  readonly providerReference: string;
  /** Hosted payment page URL (Paystack authorization_url, Flutterwave link). */
  readonly checkoutUrl?: string;
  /** Stripe PaymentIntent client secret, for an embedded payment form. */
  readonly clientSecret?: string;
  /** The provider's raw response, preserved for audit. Never used for logic. */
  readonly raw: unknown;
}

/** Normalized outcome of querying a charge's current provider-side status. */
export type ChargeVerificationStatus = 'SUCCEEDED' | 'FAILED' | 'PENDING';

/**
 * The provider's current word on a charge, normalized. This is the answer
 * to "what does the provider say RIGHT NOW" — it is NOT settlement truth
 * and must never transition domain state on its own (non-negotiable:
 * webhooks settle; verification corroborates). The Payments layer uses it
 * as a defensive cross-check and as the polling fallback for webhooks lost
 * in transit.
 */
export interface ChargeVerification {
  readonly status: ChargeVerificationStatus;
  /** Same key space as {@link InitializedCharge.providerReference}. */
  readonly providerReference: string;
  /** Integer minor units as the provider reports them. */
  readonly amountMinor: number;
  readonly currency: string;
  /** When the provider says the charge succeeded, if known. */
  readonly paidAt?: Date;
  /** Provider's explanation for FAILED, audit-only text. */
  readonly failureReason?: string;
  readonly raw: unknown;
}

export interface PaymentGatewayPort {
  readonly provider: ProviderName;

  /**
   * Ask the provider to open a charge. A success Result means the provider
   * ACCEPTED the request (hosted URL minted / PaymentIntent created) — NOT
   * that any money moved.
   */
  initializeCharge(
    input: InitializeChargeInput,
  ): Promise<Result<InitializedCharge, DomainError>>;

  /**
   * Query the provider's current status for the charge identified by
   * `providerReference` (the value this port's initializeCharge returned).
   * `PENDING` covers every non-terminal state (requires_action,
   * processing, abandoned, ...) — this port never invents finer gradations
   * the domain doesn't need.
   */
  verifyCharge(
    providerReference: string,
  ): Promise<Result<ChargeVerification, DomainError>>;
}
